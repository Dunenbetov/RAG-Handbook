import { Analogy, Callout, Formula, KeyIdea, ProjectNote, Section, Tbl } from '../../components/ui'
import { Term } from '../../components/Term'

export default function Lesson() {
  return (
    <>
      <Section title="«Вроде работает» — не метрика">
        <p>
          Ты собрал пайплайн, задал три вопроса, ответы выглядят разумно. Готово? Нет. Чтобы улучшать систему, нужно измерять
          её качество числами — иначе не поймёшь, помогло твоё изменение или навредило.
        </p>
        <p>
          Начинают с метрик <strong>поиска</strong>: они дешёвые (не нужен LLM-судья), быстрые и указывают на самое частое
          место поломки. Для их подсчёта нужен размеченный набор: вопрос → какой чанк (или страница) считается правильным.
        </p>
        <Analogy>
          <p>
            Представь, что ты тренируешь ассистента, который по вопросу приносит тебе 5 книг с полки. Метрики поиска отвечают
            на вопросы: «принёс ли он вообще нужную книгу?» (Hit Rate), «какую долю нужных книг он принёс?» (Recall),
            «сколько из принесённых реально нужны?» (Precision) и «положил ли нужную книгу сверху стопки или в самый низ?»
            (MRR).
          </p>
        </Analogy>
      </Section>

      <Section title="Четыре метрики поиска">
        <ul>
          <li>
            <Term id="hit-rate">Hit Rate@k</Term> — бинарная: попал ли хоть один правильный чанк в топ-k. Самая простая и
            понятная.
          </li>
          <li>
            <Term id="recall-at-k">Recall@k</Term> — доля правильных чанков, попавших в топ-k, от всех правильных.
          </li>
          <li>
            Precision@k — доля правильных среди найденных top-k. Пара к Recall: recall — «всё ли нашли», precision — «нет ли
            мусора».
          </li>
          <li>
            <Term id="mrr">MRR</Term> — учитывает <em>позицию</em>: насколько высоко стоит первый правильный чанк.
          </li>
        </ul>
        <Formula note="N — число вопросов, rank_i — позиция первого правильного чанка в выдаче для вопроса i">
          MRR = (1/N) · Σ 1/rank_i
        </Formula>
      </Section>

      <Section title="Считаем MRR руками">
        <p>Три вопроса, для каждого известна позиция первого правильного чанка в выдаче top-5:</p>
        <Tbl
          head={['Вопрос', 'Позиция правильного чанка', 'Reciprocal Rank']}
          rows={[
            ['«Что говорит статья 52?»', '1-е место', '1/1 = 1.0'],
            ['«Сколько дней отпуска положено?»', '3-е место', '1/3 ≈ 0.33'],
            ['«Могут ли уволить на больничном?»', 'не найден в топ-5', '0'],
          ]}
        />
        <p>
          MRR = (1.0 + 0.33 + 0) / 3 ≈ <strong>0.44</strong>. А Hit Rate@5 = 2/3 ≈ <strong>0.67</strong> (для двух вопросов
          из трёх правильный чанк вообще попал в выдачу).
        </p>
        <Callout type="info" title="Зачем MRR, если есть Hit Rate?">
          <p>
            Позиция важна: LLM внимательнее читает начало контекста, а если ты показываешь источники пользователю — первый
            результат видят все. Два пайплайна с одинаковым Hit Rate могут сильно отличаться по MRR — второй просто прячет
            правильный ответ на пятое место.
          </p>
        </Callout>
      </Section>

      <Section title="Реальные числа с семинара">
        <p>
          Пайплайн модуля 1 (юрист по кодексам РК) на 10 размеченных вопросах показал <strong>Hit Rate@5 = 0.9</strong> и{' '}
          <strong>MRR = 0.78</strong>. Читаем: для 9 вопросов из 10 нужная статья была в топ-5, и в среднем стояла между 1-м и
          2-м местом. Единственный промах — как раз вопрос с точным номером статьи, который завалил векторный поиск. Вот так
          метрики не просто оценивают систему, а <em>указывают, что чинить</em>: здесь — добавлять BM25.
        </p>
      </Section>

      <ProjectNote>
        <p>
          В Project 4 метрики поиска пригодятся для отладки (быстро сравнить конфигурации без затрат на LLM-судью), но
          официальная оценка идёт по 4 метрикам RAGAS — среди них Context Recall и Context Precision, прямые «родственники»
          сегодняшних Recall и Precision. Разберём их в главе 3.
        </p>
      </ProjectNote>

      <KeyIdea>
        Метрики поиска отвечают на два вопроса: нашли ли правильные чанки (Hit Rate, Recall) и насколько высоко они стоят
        (MRR). Они дешёвые, считаются без LLM и первыми говорят, где ломается пайплайн.
      </KeyIdea>
    </>
  )
}
